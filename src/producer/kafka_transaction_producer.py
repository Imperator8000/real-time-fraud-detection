# CLI
# ============================================================

def parse_arguments() -> argparse.Namespace:

    parser = argparse.ArgumentParser(
        description=(
            "Continuously generate synthetic financial "
            "transactions and publish them to Kafka."
        )
    )

    parser.add_argument(
        "--rate",
        type=float,
        default=25.0,
        help=(
            "Target transactions per second."
        ),
    )

    parser.add_argument(
        "--duration",
        type=float,
        default=None,
        help=(
            "Optional run duration in seconds. "
            "Without this option the producer runs "
            "until Ctrl+C."
        ),
    )

    parser.add_argument(
        "--max-events",
        type=int,
        default=None,
        help=(
            "Optional maximum number of transactions."
        ),
    )

    parser.add_argument(
        "--users",
        type=int,
        default=2_000,
        help=(
            "Number of simulated user profiles."
        ),
    )

    parser.add_argument(
        "--fraud-rate",
        type=float,
        default=0.02,
        help=(
            "Probability of generating a fraud scenario."
        ),
    )

    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help=(
            "Random seed for reproducible simulations."
        ),
    )

    arguments = (
        parser.parse_args()
    )

    if arguments.rate <= 0:

        parser.error(
            "--rate must be greater than zero."
        )

    if (
        arguments.duration is not None
        and arguments.duration <= 0
    ):

        parser.error(
            "--duration must be greater than zero."
        )

    if (
        arguments.max_events is not None
        and arguments.max_events <= 0
    ):

        parser.error(
            "--max-events must be greater than zero."
        )

    return arguments


def main() -> None:

    arguments = (
        parse_arguments()
    )

    try:

        run_producer(
            events_per_second=(
                arguments.rate
            ),
            duration_seconds=(
                arguments.duration
            ),
            maximum_events=(
                arguments.max_events
            ),
            number_of_users=(
                arguments.users
            ),
            fraud_rate=(
                arguments.fraud_rate
            ),
            seed=(
                arguments.seed
            ),
        )

    except KafkaException as error:

        raise SystemExit(
            f"Kafka producer failed: {error}"
        ) from error


if __name__ == "__main__":
    main()